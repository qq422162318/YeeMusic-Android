// Factory default API endpoint. The user can change this at runtime in
// Settings → Network, so this only matters for the first launch.
val apiBaseUrl: String =
    (findProperty("apiBaseUrl") as? String)
        ?: (findProperty("VITE_API_BASE_URL") as? String)
        ?: "http://116.205.124.216:4000"

/**
 * Hosts/IPs reachable over plain HTTP.
 *
 * Android parses NetworkSecurityConfig once at process start and offers no API
 * to change it afterwards, so the cleartext policy has to be baked in at build
 * time — a runtime switch cannot actually work, no matter how it is wired.
 *
 * The factory node above is HTTP-only (NeteaseCloudMusicAPI Enhanced usually
 * ships without TLS), so its host is always permitted. `-PcleartextHosts` adds
 * more, which is what makes a runtime node switch useful for nodes the user
 * picks later in Settings → Network.
 */
/**
 * Hosts that serve the audio bytes themselves, independent of which API node is
 * configured.
 *
 * `/song/url` answers with http:// URLs on a rotating set of CDN hosts —
 * m7/m8/m701/m702/m801/m802.music.126.net are all live right now — and NetEase
 * offers no HTTPS variant to fall back to. If only the node is permitted, every
 * track dies with an opaque ExoPlayer "ERROR_CODE_IO_UNSPECIFIED", because the
 * policy below is derived from the node alone and Android refuses the socket to
 * the CDN before ExoPlayer can even probe the format.
 *
 * `-PmediaHosts=a.com,b.com` replaces the list; defaults cover the CDN fronts
 * in use today.
 */
val mediaHosts: List<String> =
    (findProperty("mediaHosts") as? String)
        ?.split(',')
        ?.map { it.trim() }
        ?.filter { it.isNotEmpty() }
        .orEmpty()
        .ifEmpty {
            listOf(
                // Wildcard covers m7/m8/m701/m702/m801/m802.music.126.net (audio)
                // and p3/p4.music.126.net (covers).
                "music.126.net",
                "music.126.com",
                "music.163.com",
                // Newer CDN fronts: mcs.tsdm.cn, mcs.pt.tfdtb.com.
                "tsdm.cn",
                "tfdtb.com",
                // NetEase NOS object storage — where cloud-drive uploads go.
                // The upload URL is issued by /cloud/upload/token and is plain
                // HTTP on a rotating set of nosup-*.127.net fronts; the file
                // bytes never touch the API node. Without this, every upload
                // dies with a CLEARTEXT error before a single byte is sent.
                "127.net",
            )
        }

val cleartextHosts: List<String> = run {
    val nodeHost = apiBaseUrl.takeIf { it.startsWith("http://") }
        ?.removePrefix("http://")
        ?.substringBefore('/')
        ?.substringBefore(':')
        .orEmpty()
    val extra = (findProperty("cleartextHosts") as? String)
        ?.split(',')
        ?.map { it.trim() }
        ?.filter { it.isNotEmpty() }
        .orEmpty()
    (listOf(nodeHost) + extra + mediaHosts).filter { it.isNotEmpty() }.distinct()
}

/**
 * The manifest pins `@xml/network_security_config` to a fixed resource name, so
 * there is exactly one source of truth for the policy: this generated file. The
 * committed copy under src/main/res/xml/ was removed for the same reason.
 */
val networkConfigOut =
    layout.buildDirectory.file("generated/networkconfig/xml/network_security_config.xml")

tasks.register("generateNetworkSecurityConfig") {
    inputs.property("cleartextHosts", cleartextHosts)
    outputs.file(networkConfigOut)
    doLast {
        val file = networkConfigOut.get().asFile
        file.parentFile.mkdirs()
        file.writeText(renderNetworkSecurityConfig(cleartextHosts))
    }
}

fun renderNetworkSecurityConfig(hosts: List<String>): String = buildString {
    appendLine("<?xml version=\"1.0\" encoding=\"utf-8\"?>")
    appendLine("<!--")
    appendLine("    Generated by app/build.gradle.kts — do not edit by hand.")
    appendLine("")
    appendLine("    Baseline is HTTPS-only. Plaintext is permitted for loopback and private")
    appendLine("    networks, because a self-hosted NeteaseCloudMusicAPI is commonly reachable")
    appendLine("    as http://localhost:3000 or http://192.168.x.x:3000, for the API nodes")
    appendLine("    named by -PapiBaseUrl / -PcleartextHosts, and for the audio CDN hosts")
    appendLine("    named by -PmediaHosts — NetEase serves the .mp3 bytes over plain HTTP on")
    appendLine("    a rotating set of CDN hosts, so playback needs them as much as the node.")
    appendLine("-->")
    appendLine("<network-security-config>")
    appendLine("    <base-config cleartextTrafficPermitted=\"false\">")
    appendLine("        <trust-anchors>")
    appendLine("            <certificates src=\"system\" />")
    appendLine("        </trust-anchors>")
    appendLine("    </base-config>")
    appendLine("")
    appendLine("    <domain-config cleartextTrafficPermitted=\"true\">")
    appendLine("        <domain includeSubdomains=\"true\">localhost</domain>")
    appendLine("        <domain includeSubdomains=\"true\">127.0.0.1</domain>")
    appendLine("        <domain includeSubdomains=\"true\">10.0.2.2</domain>")
    appendLine("    </domain-config>")
    appendLine("")
    appendLine("    <!--")
    appendLine("        Private-network nodes (192.168.x.x / 172.16.x.x / 169.254.x.x) are")
    appendLine("        deliberately NOT listed here. Android's <domain> accepts hostnames")
    appendLine("        and single IPs, not CIDR ranges, so \"192.168.0.0/16\" is an invalid")
    appendLine("        entry that can fail the whole NetworkSecurityConfig parse, falling")
    appendLine("        back to the HTTPS-only default and killing every plaintext image.")
    appendLine("        For a private node, pass -PcleartextHosts=192.168.1.50 at build time.")
    appendLine("    -->")
    hosts.forEach { host ->
        val isIp = host.matches(Regex("[0-9]+(\\.[0-9]+){3}"))
        appendLine("")
        appendLine("    <!-- Cleartext ${if (isIp) "IP node" else "node"}: $host -->")
        appendLine("    <domain-config cleartextTrafficPermitted=\"true\">")
        // Android's XmlConfigSource rejects a <domain-config> that has no
        // <domain> child — <ip-addresses> alone does not count — so IPs are
        // emitted as exact-match <domain> entries instead. A bare IPv4 in
        // <domain> is matched literally, which is the right semantic for a
        // single-node API.
        appendLine("        <domain includeSubdomains=\"${if (isIp) "false" else "true"}\">$host</domain>")
        appendLine("    </domain-config>")
    }
    appendLine("</network-security-config>")
}

